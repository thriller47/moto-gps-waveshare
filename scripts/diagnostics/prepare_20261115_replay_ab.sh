#!/usr/bin/env bash
# Prepare two independent LVGL/WebAssembly replay builds for a controlled
# comparison. No reset/clean/checkout of the user's active working tree.
set -euo pipefail

repo_dir="$(cd "$(dirname "$0")/../.." && pwd)"
output_dir="$HOME/MotoGPS/motogps-regression-20261117"
baseline_dir="$output_dir/baseline"
current_dir="$output_dir/current"
baseline_ref="refs/remotes/origin/diagnostics/baseline-20261115"
current_ref="refs/remotes/origin/test/unified-offline-map-20261115"
expected_baseline="e1cc5cdf7695f22b0b8485d91572ea5864dfc6a7"

if [[ $# -ne 0 ]]; then
  echo "Usage: bash scripts/diagnostics/prepare_20261115_replay_ab.sh" >&2
  exit 2
fi
if [[ ! -f "$HOME/emsdk/emsdk_env.sh" ]]; then
  echo "Missing $HOME/emsdk/emsdk_env.sh: install/activate existing Emscripten first" >&2
  exit 1
fi

echo "Fetching immutable reference and latest experimental branch..."
git -C "$repo_dir" fetch origin --prune
baseline_sha="$(git -C "$repo_dir" rev-parse "$baseline_ref^{commit}")"
current_sha="$(git -C "$repo_dir" rev-parse "$current_ref^{commit}")"
if [[ "$baseline_sha" != "$expected_baseline" ]]; then
  echo "Baseline ref moved unexpectedly. Refusing comparison." >&2
  exit 1
fi

prepare_worktree() {
  local label="$1" target="$2" sha="$3" actual
  if [[ -e "$target" ]]; then
    if ! git -C "$target" rev-parse --show-toplevel >/dev/null 2>&1; then
      echo "$target exists but is not a Git worktree. No files changed." >&2
      exit 1
    fi
    actual="$(git -C "$target" rev-parse HEAD)"
    if [[ "$actual" != "$sha" ]]; then
      echo "$target points to $actual, expected $sha." >&2
      echo "Do not reset it: use a new output directory for another revision." >&2
      exit 1
    fi
    if [[ -n "$(git -C "$target" status --porcelain)" ]]; then
      echo "$target has local changes; refusing to modify them." >&2
      exit 1
    fi
  else
    git -C "$repo_dir" worktree add --detach "$target" "$sha"
  fi
  echo "$label: $sha"
  git -C "$target" submodule update --init --recursive
}

mkdir -p "$output_dir"
prepare_worktree "BASELINE 15/11" "$baseline_dir" "$baseline_sha"
prepare_worktree "TEST CURRENT" "$current_dir" "$current_sha"

if ! cmp -s "$baseline_dir/platforms/web/simulator/trace_model.js" \
              "$current_dir/platforms/web/simulator/trace_model.js"; then
  echo "WARNING: replay parsers differ; compare cautiously." >&2
else
  echo "Same JSONL replay parser on both versions."
fi

# Emscripten from the established local WSL install.
source "$HOME/emsdk/emsdk_env.sh"
command -v emcmake >/dev/null
export CMAKE_BUILD_PARALLEL_LEVEL=2

for target in "$baseline_dir" "$current_dir"; do
  echo "Building LVGL/WASM in $target..."
  bash "$target/scripts/build_web.sh"
  test -s "$target/platforms/web/shell/runtime/moto-gps-device.js"
  test -s "$target/platforms/web/shell/runtime/moto-gps-device.wasm"
done

cat <<EOF
Two independent builds are ready. Open TWO other WSL terminals.

Terminal BASELINE:
  python3 -m http.server 4174 --directory "$baseline_dir"

Terminal CURRENT:
  python3 -m http.server 4175 --directory "$current_dir"

Browser BASELINE:
  http://127.0.0.1:4174/platforms/web/simulator/index.html
Browser CURRENT:
  http://127.0.0.1:4175/platforms/web/simulator/index.html

Load the SAME exported 17 Nov JSONL replay in each browser.
At 1x, use original recorded heading and disable optional zoom/predictor
experiments where available. Use Ctrl+F5 after rebuilding.

IMPORTANT: The JSONL already contains MANEUVER, distance and route geometry
generated by 17 Nov Android. This compares WASM/rendering, NOT the actual
15 Nov vs 17 Nov Android map-matching or real ESP32 gyroscope.
No existing branches, phone builds, GPS files or map data were changed.
EOF
